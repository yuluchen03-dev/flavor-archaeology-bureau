function normalizeName(name = '') {
  return String(name).trim();
}

class DishVisualPromptService {
  static getSpec(dishName = '') {
    const name = normalizeName(dishName);
    return DISH_VISUAL_SPECS[name] || DEFAULT_SPEC;
  }

  static buildPrompt({ dishName = '历史风味菜品', prompt = '', extra = '' } = {}) {
    const spec = this.getSpec(dishName);
    const base = prompt || `${dishName}复原成品图`;
    return [
      `${dishName}。${base}`,
      `古籍或复原依据：${spec.evidence}`,
      `菜品视觉事实：${spec.visualIdentity}`,
      `实物参考形态：${spec.referenceShape}`,
      `镜头构图：${spec.composition}`,
      `必须出现：${spec.mustInclude.join('；')}。`,
      `必须避免：${spec.mustAvoid.join('；')}。`,
      extra,
      '最终画面必须是一道真实可食用、已经熟制并能上桌的中式菜品，不是食材展示、不是博物馆模型、不是概念海报。',
    ].filter(Boolean).join(' ');
  }

  static buildSourceFacts(dishName = '') {
    const spec = this.getSpec(dishName);
    return `${dishName}视觉事实：${spec.visualIdentity}；实物形态：${spec.referenceShape}；构图：${spec.composition}；关键元素：${spec.mustInclude.join('、')}；禁忌：${spec.mustAvoid.join('、')}。`;
  }
}

DishVisualPromptService.SPECS = DISH_VISUAL_SPECS;

module.exports = DishVisualPromptService;
